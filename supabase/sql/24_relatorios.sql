-- =====================================================================
-- 24_relatorios.sql
-- Relatórios de desempenho do Instagram (contas com o recurso
-- 'relatorios' em ig_contas.recursos).
-- - metricas_diarias: seguidores do dia (a Meta não guarda o passado:
--   só dá o número de agora), alcance e novos seguidores por dia
-- - metricas_posts: as métricas mais recentes de cada post
-- - relatorios: semanal (segunda, da semana anterior) e mensal (dia 1º,
--   do mês anterior), salvos com histórico
-- - coletas: cada vez que o robô buscou os dados, e se deu certo
-- Quem escreve é só a função ig-relatorios (chave de serviço).
-- Quem lê: membros da conta.
--
-- Rode depois do 23_ficha_conteudo.sql. Pode rodar de novo sem estragar.
-- O agendamento (pg_cron) é criado à parte, copiando a chave do ig-scheduler.
-- =====================================================================

create table if not exists public.metricas_diarias (
  conta_id          uuid not null references public.ig_contas(id) on delete cascade,
  dia               date not null,
  seguidores        int,            -- foto do dia (só existe a partir da 1ª coleta)
  alcance           int,
  novos_seguidores  int,            -- ganhos do dia (a Meta não desconta quem saiu)
  atualizado_em     timestamptz not null default now(),
  primary key (conta_id, dia)
);

create table if not exists public.metricas_posts (
  conta_id          uuid not null references public.ig_contas(id) on delete cascade,
  media_id          text not null,
  publicado_em      timestamptz,
  tipo              text,           -- Reels, Carrossel, Foto, Vídeo
  link              text,
  legenda           text,
  miniatura         text,
  curtidas          int,
  comentarios       int,
  salvos            int,
  compartilhamentos int,
  alcance           int,
  views             int,
  interacoes        int,
  seguidores        int,            -- seguidores que vieram pelo post (quando a Meta dá)
  visitas_perfil    int,            -- idem
  tempo_medio_s     numeric,        -- Reels: tempo médio assistido (segundos)
  atualizado_em     timestamptz not null default now(),
  primary key (conta_id, media_id)
);
create index if not exists metricas_posts_data_idx on public.metricas_posts (conta_id, publicado_em);

create table if not exists public.relatorios (
  id          uuid primary key default gen_random_uuid(),
  conta_id    uuid not null references public.ig_contas(id) on delete cascade,
  tipo        text not null check (tipo in ('semanal', 'mensal', 'personalizado')),
  inicio      date not null,
  fim         date not null,
  dados       jsonb not null default '{}',
  analise     jsonb,                -- sugestões da IA (resumo, hipóteses, recomendações)
  status      text not null default 'ok' check (status in ('ok', 'parcial', 'erro')),
  avisos      text[] not null default '{}',
  origem      text not null default 'automatico' check (origem in ('automatico', 'manual')),
  gerado_em   timestamptz not null default now(),
  unique (conta_id, tipo, inicio, fim)
);

create table if not exists public.coletas (
  id        bigint generated by default as identity primary key,
  conta_id  uuid not null references public.ig_contas(id) on delete cascade,
  quando    timestamptz not null default now(),
  ok        boolean not null,
  detalhe   text
);
create index if not exists coletas_conta_idx on public.coletas (conta_id, quando desc);

do $$
declare t text;
begin
  foreach t in array array['metricas_diarias', 'metricas_posts', 'relatorios', 'coletas'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('revoke insert, update, delete on public.%I from authenticated', t);
    execute format('grant select on public.%I to authenticated', t);
    execute format('drop policy if exists "ler_membros" on public.%I', t);
    execute format('create policy "ler_membros" on public.%I for select to authenticated using (conta_id in (select public.minhas_contas()))', t);
  end loop;
end $$;

-- coletas antigas não precisam ficar para sempre
create or replace function public.limpar_coletas()
returns void
language sql
security definer
set search_path = public
as $$ delete from coletas where quando < now() - interval '90 days' $$;
