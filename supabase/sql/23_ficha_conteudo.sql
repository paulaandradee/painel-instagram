-- 23_ficha_conteudo.sql
-- Ficha completa de conteúdo, tarefas, comentários, histórico e
-- campanhas. Vale para as contas com o recurso 'producao' em
-- ig_contas.recursos; as outras continuam com o calendário simples.
-- - conteudos ganha: número único, título, pilar, objetivo, origem
--   (autoral/remix...), campanha, horário, responsáveis, etapa de
--   produção (18 etapas), briefing, roteiro, capa, CTA, referências,
--   pasta do Drive, link e ID do post no Instagram
-- - tarefas: roteiro, arte, gravação, edição, aprovação, agendamento,
--   análise e compromissos, com data, hora e responsável
-- - historico: o banco anota quem mudou o quê e quando (não depende da tela)
-- Leitura: membros da conta. Escrita: quem edita (não "só visualização").
--
-- Rode depois do 22_formacao.sql. Pode rodar de novo sem estragar.
-- =====================================================================

-- ---------- Campanhas ----------
create table if not exists public.campanhas (
  id          uuid primary key default gen_random_uuid(),
  conta_id    uuid not null references public.ig_contas(id) on delete cascade,
  nome        text not null,
  inicio      date,
  lancamento  date,
  fim         date,
  objetivo    text not null default '',
  mensagem    text not null default '',
  notas       text not null default '',
  criado_em   timestamptz not null default now()
);

-- ---------- Conteúdo: campos da ficha ----------
alter table public.conteudos
  add column if not exists numero           bigint generated by default as identity,
  add column if not exists titulo           text not null default '',
  add column if not exists pilar            text not null default '',
  add column if not exists objetivo         text not null default '',
  add column if not exists origem           text check (origem in ('autoral', 'remix', 'curadoria', 'terceiros', 'ia')),
  add column if not exists campanha_id      uuid references public.campanhas(id) on delete set null,
  add column if not exists hora             time,
  add column if not exists resp_estrategia  uuid references auth.users(id) on delete set null,
  add column if not exists resp_gravacao    uuid references auth.users(id) on delete set null,
  add column if not exists resp_edicao      uuid references auth.users(id) on delete set null,
  add column if not exists resp_aprovacao   uuid references auth.users(id) on delete set null,
  add column if not exists etapa            text not null default 'ideia',
  add column if not exists briefing         text not null default '',
  add column if not exists roteiro          text not null default '',
  add column if not exists capa_texto       text not null default '',
  add column if not exists cta              text not null default '',
  add column if not exists referencias      text not null default '',
  add column if not exists drive_pasta_url  text not null default '',
  add column if not exists link_publicacao  text not null default '',
  add column if not exists ig_media_id      text;

alter table public.conteudos drop constraint if exists conteudos_etapa_check;
alter table public.conteudos add constraint conteudos_etapa_check check (etapa in (
  'ideia', 'planejamento', 'roteiro_andamento', 'roteiro_pronto', 'aguardando_gravacao', 'gravando',
  'gravado', 'aguardando_edicao', 'em_edicao', 'editado', 'aguardando_aprovacao', 'ajustes_solicitados',
  'aprovado', 'pronto_agendar', 'agendado', 'publicado', 'em_analise', 'finalizado'));
create unique index if not exists conteudos_numero_idx on public.conteudos (numero);

-- A etapa puxa o status simples (o calendário antigo e os contadores usam)
create or replace function public.conteudos_etapa_status()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' or new.etapa is distinct from old.etapa then
    if new.etapa in ('publicado', 'em_analise', 'finalizado') then
      new.status := 'publicado'; new.etapa_publicado := true;
    elsif new.etapa in ('aprovado', 'pronto_agendar', 'agendado') then
      new.status := 'pronto';
    elsif new.etapa <> 'ideia' then
      new.status := 'a_fazer';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists conteudos_etapa_status on public.conteudos;
create trigger conteudos_etapa_status before insert or update on public.conteudos
  for each row execute function public.conteudos_etapa_status();

-- ---------- Tarefas ----------
create table if not exists public.tarefas (
  id           uuid primary key default gen_random_uuid(),
  conta_id     uuid not null references public.ig_contas(id) on delete cascade,
  conteudo_id  uuid references public.conteudos(id) on delete cascade,
  tipo         text not null default 'outro' check (tipo in
               ('roteiro', 'arte', 'gravacao', 'edicao', 'aprovacao', 'agendamento', 'analise', 'compromisso', 'outro')),
  titulo       text not null default '',
  data         date,
  hora         time,
  responsavel  uuid references auth.users(id) on delete set null,
  status       text not null default 'a_fazer' check (status in ('a_fazer', 'fazendo', 'feita')),
  notas        text not null default '',
  criado_por   uuid default auth.uid() references auth.users(id) on delete set null,
  criado_em    timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index if not exists tarefas_data_idx on public.tarefas (conta_id, data);
create index if not exists tarefas_conteudo_idx on public.tarefas (conteudo_id);
drop trigger if exists tarefas_atualizado on public.tarefas;
create trigger tarefas_atualizado before update on public.tarefas
  for each row execute function public.conteudos_atualizado();

-- ---------- Comentários internos ----------
create table if not exists public.conteudo_comentarios (
  id           uuid primary key default gen_random_uuid(),
  conta_id     uuid not null references public.ig_contas(id) on delete cascade,
  conteudo_id  uuid not null references public.conteudos(id) on delete cascade,
  autor        uuid default auth.uid() references auth.users(id) on delete set null,
  texto        text not null check (length(texto) between 1 and 4000),
  tipo         text not null default 'comentario' check (tipo in ('comentario', 'ajuste', 'aprovacao')),
  criado_em    timestamptz not null default now()
);
create index if not exists comentarios_conteudo_idx on public.conteudo_comentarios (conteudo_id, criado_em);

-- ---------- Histórico (escrito só pelo banco) ----------
create table if not exists public.conteudo_historico (
  id           bigint generated by default as identity primary key,
  conta_id     uuid not null references public.ig_contas(id) on delete cascade,
  conteudo_id  uuid not null references public.conteudos(id) on delete cascade,
  quem         uuid references auth.users(id) on delete set null,
  quando       timestamptz not null default now(),
  campo        text not null,
  antes        text,
  depois       text
);
create index if not exists historico_conteudo_idx on public.conteudo_historico (conteudo_id, quando desc);

create or replace function public.conteudo_registrar()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  campos text[] := array['titulo','tema','pilar','objetivo','formato','origem','campanha_id','data','hora','etapa',
    'resp_estrategia','resp_gravacao','resp_edicao','resp_aprovacao','briefing','roteiro','capa_texto','legenda',
    'cta','referencias','drive_pasta_url','link_publicacao','ig_media_id','notas'];
  c text; a text; d text;
begin
  if tg_op = 'INSERT' then
    insert into conteudo_historico (conta_id, conteudo_id, quem, campo, depois)
    values (new.conta_id, new.id, auth.uid(), 'criado', coalesce(nullif(new.titulo, ''), new.tema));
    return new;
  end if;
  foreach c in array campos loop
    execute format('select ($1).%I::text, ($2).%I::text', c, c) into a, d using old, new;
    if a is distinct from d then
      insert into conteudo_historico (conta_id, conteudo_id, quem, campo, antes, depois)
      values (new.conta_id, new.id, auth.uid(), c, left(a, 300), left(d, 300));
    end if;
  end loop;
  return new;
end $$;
drop trigger if exists conteudo_registrar on public.conteudos;
create trigger conteudo_registrar after insert or update on public.conteudos
  for each row execute function public.conteudo_registrar();

create or replace function public.tarefa_registrar()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare r record; o text;
begin
  r := coalesce(new, old);
  if r.conteudo_id is null then return r; end if;
  if tg_op = 'DELETE' then
    o := 'tarefa removida';
  elsif tg_op = 'INSERT' then
    o := 'tarefa criada';
  elsif new.status is distinct from old.status or new.data is distinct from old.data or new.responsavel is distinct from old.responsavel then
    o := 'tarefa alterada';
  else
    return r;
  end if;
  -- o conteúdo pode estar sendo apagado junto (cascade)
  if not exists (select 1 from conteudos where id = r.conteudo_id) then return r; end if;
  insert into conteudo_historico (conta_id, conteudo_id, quem, campo, antes, depois)
  values (r.conta_id, r.conteudo_id, auth.uid(), o,
          case when tg_op = 'UPDATE' then concat_ws(' · ', old.status, old.data::text) end,
          concat_ws(' · ', r.tipo, nullif(r.titulo, ''), r.status, r.data::text));
  return r;
end $$;
drop trigger if exists tarefa_registrar on public.tarefas;
create trigger tarefa_registrar after insert or update or delete on public.tarefas
  for each row execute function public.tarefa_registrar();

-- ---------- Quem é da conta (para escolher responsável) ----------
create or replace function public.membros_da_conta(p_conta uuid)
returns table (user_id uuid, email text)
language sql
stable
security definer
set search_path = public
as $$
  select m.user_id, u.email::text
  from ig_membros m join auth.users u on u.id = m.user_id
  where m.conta_id = p_conta and p_conta in (select public.minhas_contas())
  order by u.email
$$;
revoke all on function public.membros_da_conta(uuid) from anon;
grant execute on function public.membros_da_conta(uuid) to authenticated;

-- ---------- Regras de acesso ----------
do $$
declare t text;
begin
  foreach t in array array['campanhas', 'tarefas', 'conteudo_comentarios', 'conteudo_historico'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('drop policy if exists "ler_membros" on public.%I', t);
    execute format('create policy "ler_membros" on public.%I for select to authenticated using (conta_id in (select public.minhas_contas()))', t);
  end loop;
  foreach t in array array['campanhas', 'tarefas', 'conteudo_comentarios'] loop
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('drop policy if exists "incluir_editores" on public.%I', t);
    execute format('create policy "incluir_editores" on public.%I for insert to authenticated with check (conta_id in (select public.contas_que_edito()))', t);
    execute format('drop policy if exists "alterar_editores" on public.%I', t);
    execute format('create policy "alterar_editores" on public.%I for update to authenticated using (conta_id in (select public.contas_que_edito())) with check (conta_id in (select public.contas_que_edito()))', t);
    execute format('drop policy if exists "apagar_editores" on public.%I', t);
    execute format('create policy "apagar_editores" on public.%I for delete to authenticated using (conta_id in (select public.contas_que_edito()))', t);
  end loop;
end $$;
grant select on public.conteudo_historico to authenticated;   -- só o banco escreve

-- Comentário: só o autor apaga ou edita o próprio
