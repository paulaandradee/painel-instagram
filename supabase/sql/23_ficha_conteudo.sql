create policy "alterar_editores" on public.conteudo_comentarios for update to authenticated
  using (autor = auth.uid()) with check (autor = auth.uid());
drop policy if exists "apagar_editores" on public.conteudo_comentarios;
create policy "apagar_editores" on public.conteudo_comentarios for delete to authenticated
  using (autor = auth.uid());
